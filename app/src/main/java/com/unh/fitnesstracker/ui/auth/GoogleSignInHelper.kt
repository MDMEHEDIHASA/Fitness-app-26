package com.unh.fitnesstracker.ui.auth

import android.annotation.SuppressLint
import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential

sealed interface GoogleSignInOutcome {
    data class Success(val idToken: String) : GoogleSignInOutcome
    data object Cancelled : GoogleSignInOutcome
    data class Failure(val message: String) : GoogleSignInOutcome
}

/** Shows the Google account picker through Credential Manager and returns the ID token. */
object GoogleSignInHelper {

    suspend fun requestIdToken(context: Context): GoogleSignInOutcome {
        val webClientId = webClientId(context)
            ?: return GoogleSignInOutcome.Failure(
                "Google sign-in is not enabled. Turn it on in Firebase Authentication and re-download google-services.json."
            )

        val googleIdOption = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(webClientId)
            .build()
        val request = GetCredentialRequest.Builder().addCredentialOption(googleIdOption).build()

        return try {
            val credential = CredentialManager.create(context).getCredential(context, request).credential
            if (credential is CustomCredential &&
                credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                GoogleSignInOutcome.Success(GoogleIdTokenCredential.createFrom(credential.data).idToken)
            } else {
                GoogleSignInOutcome.Failure("Unexpected credential type")
            }
        } catch (_: GetCredentialCancellationException) {
            GoogleSignInOutcome.Cancelled
        } catch (_: NoCredentialException) {
            GoogleSignInOutcome.Failure("No Google account found on this device")
        } catch (e: GetCredentialException) {
            GoogleSignInOutcome.Failure(e.message ?: "Google sign-in failed")
        }
    }

    /**
     * default_web_client_id is generated by the Google Services plugin from google-services.json,
     * so it is looked up at runtime instead of through R.string (it does not exist before Firebase setup).
     */
    @SuppressLint("DiscouragedApi")
    private fun webClientId(context: Context): String? {
        val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        return if (id == 0) null else context.getString(id)
    }
}
